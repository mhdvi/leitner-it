export const LEVEL_NAMES = {
  fa: { a1: 'مبتدی', a2: 'مقدماتی', b1: 'متوسط', b2: 'فوق متوسط' },
  en: { a1: 'Beginner', a2: 'Elementary', b1: 'Intermediate', b2: 'Upper-intermediate' },
};

export function lang() {
  return settings().ui === 'en' ? 'en' : 'fa';
}

export const isRtl = () => lang() === 'fa';

export function t(key, vars = {}) {
  const v = STR[lang()][key] ?? STR.en[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(vars) : v;
}

export function fmt(n) {
  return typeof n === 'number' ? n.toLocaleString(lang() === 'fa' ? 'fa-IR' : 'en-US') : n;
}

export const pct = (n) => fmt(n) + (lang() === 'fa' ? '٪' : '%');

export function dateLine(d = new Date()) {
  return lang() === 'fa'
    ? d.toLocaleDateString('fa-IR', { weekday: 'long', day: 'numeric', month: 'long' })
    : d.toLocaleDateString('en-GB', { weekday: 'long', day: 'numeric', month: 'long' });
}

export function applyLang() {
  const root = document.documentElement;
  root.lang = lang();
  root.dir = isRtl() ? 'rtl' : 'ltr';
  document.title = t('appName');
}
